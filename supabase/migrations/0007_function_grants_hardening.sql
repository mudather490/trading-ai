-- =============================================================================
-- 0007_function_grants_hardening.sql
--
-- Closes a hole found by the Supabase MCP security advisor on the live
-- project, and confirmed by hand against the anon key.
--
-- THE FINDING
--   Postgres grants EXECUTE on every new function to PUBLIC. Supabase then
--   adds explicit EXECUTE grants for `anon` and `authenticated` on all
--   functions in `public`. Migrations 0004 and 0005 only ever ADDED grants
--   (`grant execute ... to service_role`); they never revoked the defaults.
--   The result: every SECURITY DEFINER function in `public` was callable by
--   an unauthenticated caller at /rest/v1/rpc/<name>.
--
--   SECURITY DEFINER bypasses RLS, so this was not a "the grant exists but
--   the policy blocks it" situation. Confirmed against the live project with
--   the public anon key:
--
--     POST /rest/v1/rpc/record_signal  -> 200, inserted a row into public.signals
--     POST /rest/v1/rpc/claim_jobs     -> 200, executed against public.jobs
--     POST /rest/v1/rpc/fire_alert     -> 200, executed against public.alerts
--     POST /rest/v1/rpc/get_ticket     -> 200, executed against a caller-chosen
--                                          p_user_id
--
--   `public.signals` is the immutable record the Decision Center reads. An
--   anonymous caller could forge entries in it.
--
--   promote_strategy was already safe: it raises P0001 for a non-owner. That
--   was verified, not assumed.
--
-- THE FIX
--   1. Revoke EXECUTE from PUBLIC and from `anon` on every function in
--      `public`, and grant it only to the roles that need it.
--   2. Add an explicit custody guard to fire_alert() and get_ticket(), which
--      both take a caller-supplied user_id and previously trusted the caller.
--   3. Pin `search_path` on the two functions that had none
--      (function_search_path_mutable).
--   4. Stop the default privileges from granting EXECUTE to anon and
--      authenticated on functions created in future, so the hole cannot
--      reopen silently.
--
-- TABLE GRANTS ARE DELIBERATELY LEFT ALONE
--   Supabase grants table privileges to `anon` on purpose and RLS is what
--   filters rows. Every table in `public` here has RLS enabled and not one
--   policy applies to `anon` or PUBLIC, so an anonymous read returns zero
--   rows. That was verified. Revoking those grants would fight the platform's
--   model rather than close a hole.
--
-- Generated by tools/gen_hardening_migration.py. The redefined bodies are
-- byte-identical to 0001/0005 apart from the inserted guard.
-- =============================================================================

-- ------------------------------------------ set_updated_at (pinned) --
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
-- ------------------------------------------ engine_status (pinned) --
create or replace function public.engine_status()
returns jsonb
language sql
stable
set search_path = public
as $$
  select jsonb_build_object(
    'status', case
      when h.last_seen_at is null then 'never_seen'
      when now() - h.last_seen_at > interval '2 minutes' then 'stale'
      else 'live' end,
    'last_seen_at', h.last_seen_at,
    'age_seconds', extract(epoch from (now() - h.last_seen_at)),
    'worker_id', h.worker_id,
    'version', h.version,
    'streams', h.streams,
    'lag_ms', h.lag_ms
  )
  from (select * from public.worker_heartbeat order by last_seen_at desc limit 1) h;
$$;
-- ------------------------------------------- fire_alert (guarded) --
create or replace function public.fire_alert(
  p_user_id uuid,
  p_kind text,
  p_rule_id text,
  p_title text,
  p_body text default null,
  p_severity public.alert_severity default 'info',
  p_payload jsonb default '{}'::jsonb,
  p_dedupe_key text default null
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_key text;
  v_id uuid;
begin

  -- ---- custody guard ------------------------------------------------------
  -- The worker (service_role) may file an alert for anybody. A signed-in user
  -- may file one only for themselves. `anon` cannot reach this function at all:
  -- see the grants at the end of this migration.
  if not public.caller_is_privileged()
     and p_user_id is distinct from auth.uid() then
    raise exception 'Not permitted: an alert may only be filed for yourself.'
      using errcode = '42501';
  end if;
  v_key := coalesce(p_dedupe_key,
    p_kind || ':' || p_rule_id || ':' || coalesce(p_payload->>'instrument_id','') ||
    ':' || coalesce(p_payload->>'bar_close_time', now()::text));

  insert into public.alerts (user_id, kind, rule_id, title, body, severity, payload, dedupe_key)
  values (p_user_id, p_kind, p_rule_id, p_title, p_body, p_severity, p_payload, v_key)
  on conflict (dedupe_key) do nothing
  returning id into v_id;

  return v_id;
end;
$$;
-- --------------------------------------------- get_ticket (guarded) --
create or replace function public.get_ticket(
  p_user_id uuid,
  p_instrument uuid,
  p_timeframe text default '1h'
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_eng        jsonb;
  v_status     text;
  v_quote      public.latest_quotes%rowtype;
  v_signal     public.signals%rowtype;
  v_profile    public.user_profiles%rowtype;
  v_champion   public.champions%rowtype;
  v_version    public.strategy_versions%rowtype;
  v_strategy   public.strategies%rowtype;
  v_instr      public.instruments%rowtype;
  v_risk       jsonb := '{}'::jsonb;
  v_warnings   jsonb := '[]'::jsonb;
  v_tickets_today integer;
  v_open_count    integer;
  v_gross_open    numeric;
  v_risk_amount   numeric;
  v_stop_distance numeric;
  v_size_units    numeric;
  v_size_cap_units numeric;
  v_gross_cap_units numeric;
  v_size_notional numeric;
  v_rr          numeric;
  v_rr_floor    numeric := 1.0;
  v_refusal     text;
  v_catalyst    record;
  v_mid         numeric;
  v_max_age     interval;
  v_metric      jsonb;
begin

  -- ---- custody guard ------------------------------------------------------
  -- A ticket is computed from a user's capital, their open positions and their
  -- daily ticket count. It may therefore only be computed for the caller.
  -- The owner may compute one for anyone (that is the owner's job).
  if not public.caller_is_privileged()
     and p_user_id is distinct from auth.uid()
     and not public.is_owner() then
    raise exception 'Not permitted: a ticket may only be computed for yourself.'
      using errcode = '42501';
  end if;
  -- ---------------------------------------------------------------- engine --
  v_eng := public.engine_status();
  v_status := v_eng->>'status';
  if v_status is distinct from 'live' then
    return jsonb_build_object(
      'status', 'engine_unavailable',
      'reason', 'The live engine is not running. No ticket can be issued.',
      'engine', v_eng
    );
  end if;

  -- -------------------------------------------------------------- profile --
  select * into v_profile from public.user_profiles where user_id = p_user_id;
  if not found then
    return jsonb_build_object(
      'status', 'no_match',
      'reason', 'No risk profile. Complete onboarding to receive tickets.'
    );
  end if;

  -- ----------------------------------------------------------- instrument --
  select * into v_instr from public.instruments where id = p_instrument;
  if not found then
    return jsonb_build_object('status', 'no_match', 'reason', 'Unknown instrument.');
  end if;
  if not v_instr.in_universe then
    return jsonb_build_object(
      'status', 'no_match',
      'reason', format('%s is not in the trading universe.', v_instr.symbol)
    );
  end if;

  -- ---------------------------------------------------------- fresh quote --
  select * into v_quote from public.latest_quotes where instrument_id = p_instrument;
  if not found then
    return jsonb_build_object(
      'status', 'stale',
      'reason', format('No price data for %s yet.', v_instr.symbol)
    );
  end if;

  -- Freshness windows differ by asset class: crypto ticks continuously, US
  -- equities have session gaps and IEX is partial.
  v_max_age := case v_instr.asset_class
    when 'crypto' then interval '30 seconds'
    when 'forex'  then interval '2 minutes'
    when 'metal'  then interval '2 minutes'
    else interval '10 minutes'   -- us_equity: session gaps + IEX partial
  end;

  if v_quote.as_of < now() - v_max_age then
    return jsonb_build_object(
      'status', 'stale',
      'reason', format('Last price for %s is %s old. Not acting on stale data.',
                        v_instr.symbol,
                        to_char(now() - v_quote.as_of, 'MI:SS')),
      'data_as_of', v_quote.as_of,
      'age_seconds', extract(epoch from (now() - v_quote.as_of))
    );
  end if;

  -- ------------------------------------------------------ daily ticket cap --
  select count(*) into v_tickets_today
    from public.tickets
    where user_id = p_user_id and created_at >= date_trunc('day', now());
  if v_tickets_today >= v_profile.max_tickets_per_day then
    return jsonb_build_object(
      'status', 'wait',
      'reason', format('Daily ticket limit reached (%s).', v_profile.max_tickets_per_day),
      'tickets_today', v_tickets_today
    );
  end if;

  -- ------------------------------------------------- concurrent positions --
  select count(*) into v_open_count
    from public.tickets
    where user_id = p_user_id and state = 'active';
  if v_open_count >= v_profile.max_concurrent then
    return jsonb_build_object(
      'status', 'wait',
      'reason', format('Concurrent position limit reached (%s).', v_profile.max_concurrent),
      'open_tickets', v_open_count
    );
  end if;

  -- ------------------------------------------------------- champion lookup --
  -- Only a PROMOTED champion for this asset class + timeframe may produce a
  -- ticket. An unregistered strategy can never become advice (I-5, condition 3).
  select c.* into v_champion
    from public.champions c
    join public.strategy_versions sv on sv.id = c.version_id
    join public.strategies s on s.id = sv.strategy_id
    where c.asset_class = v_instr.asset_class
      and c.timeframe = p_timeframe
      and c.active
      and sv.status = 'champion'
    limit 1;

  if not found then
    return jsonb_build_object(
      'status', 'no_match',
      'reason', format('No promoted %s strategy on the %s timeframe yet.',
                        v_instr.asset_class, p_timeframe),
      'instrument', v_instr.symbol
    );
  end if;

  select * into v_version   from public.strategy_versions where id = v_champion.version_id;
  select * into v_strategy  from public.strategies      where id = v_version.strategy_id;
  v_risk := coalesce(v_version.risk_spec, '{}'::jsonb);
  v_rr_floor := coalesce((v_risk->>'min_reward_risk')::numeric, 1.0);

  -- ------------------------------------------------------ active signal ----
  select * into v_signal
    from public.signals
    where instrument_id = p_instrument
      and timeframe = p_timeframe
      and status = 'active'
      and (p_timeframe = '1d' or bar_close_time > now() - interval '15 minutes')
      and (expires_at is null or expires_at > now())
    order by bar_close_time desc
    limit 1;

  if not found then
    return jsonb_build_object(
      'status', 'wait',
      'reason', format('No %s setup for %s right now. The champion is waiting.',
                        p_timeframe, v_instr.symbol),
      'instrument', v_instr.symbol,
      'strategy', v_strategy.name,
      'strategy_version', v_version.version
    );
  end if;

  if v_signal.side = 'flat' then
    return jsonb_build_object(
      'status', 'wait',
      'reason', format('The champion is flat on %s.', v_instr.symbol),
      'instrument', v_instr.symbol
    );
  end if;

  -- ------------------------------------------------------------- sizing ----
  v_mid := case
    when v_signal.entry_low is not null and v_signal.entry_high is not null
      then (v_signal.entry_low + v_signal.entry_high) / 2
    else v_signal.entry_price
  end;

  if v_signal.stop_price is null or v_mid is null or v_signal.stop_price >= v_mid then
    return jsonb_build_object(
      'status', 'wait',
      'reason', 'The setup has no valid stop. Refusing to size it.',
      'instrument', v_instr.symbol
    );
  end if;

  v_stop_distance := abs(v_mid - v_signal.stop_price);
  if v_stop_distance = 0 then
    return jsonb_build_object(
      'status', 'wait',
      'reason', 'Stop distance is zero. Refusing to size it.',
      'instrument', v_instr.symbol
    );
  end if;

  v_risk_amount := coalesce(v_profile.capital_usd, 0) * v_profile.risk_per_trade_pct;

  if v_profile.capital_usd is null or v_profile.capital_usd <= 0 then
    -- No capital set: we can still publish the ticket with per-unit sizing.
    v_size_units := null;
    v_size_notional := null;
  else
    v_size_units := floor(v_risk_amount / v_stop_distance);
    -- Position cap
    v_size_cap_units := floor(
      (v_profile.capital_usd * v_profile.max_position_pct) / v_mid);
    -- Gross exposure cap
    select coalesce(sum(coalesce(size_notional, 0)), 0) into v_gross_open
      from public.tickets where user_id = p_user_id and state = 'active';
    v_gross_cap_units := floor(
      greatest(coalesce(v_profile.capital_usd, 0) * v_profile.max_gross_pct - v_gross_open, 0)
      / v_mid);
    v_size_units := least(coalesce(v_size_units, v_size_cap_units),
                          v_size_cap_units, v_gross_cap_units);
    if v_size_units <= 0 then
      v_refusal := case
        when v_gross_cap_units <= 0 then 'Gross exposure cap reached.'
        when v_size_cap_units <= 0 then 'Position size cap reached.'
        else 'The stop is too far away to size within the risk budget.'
      end;
      return jsonb_build_object(
        'status', 'wait',
        'reason', v_refusal,
        'instrument', v_instr.symbol,
        'risk_budget_usd', v_risk_amount,
        'stop_distance', v_stop_distance
      );
    end if;
    v_size_notional := v_size_units * v_mid;
  end if;

  -- ------------------------------------------------------ reward : risk ----
  v_rr := case
    when v_signal.target_price is null then null
    else abs(v_signal.target_price - v_mid) / v_stop_distance
  end;

  if v_rr is not null and v_rr < v_rr_floor then
    return jsonb_build_object(
      'status', 'wait',
      'reason', format('Reward:risk %s is below the %s floor. Not worth taking.',
                        to_char(v_rr, 'FM990.00'), to_char(v_rr_floor, 'FM990.00')),
      'instrument', v_instr.symbol,
      'reward_risk', v_rr,
      'rr_floor', v_rr_floor
    );
  end if;

  -- ------------------------------------------------------ news risk flag ---
  -- News NEVER changes the size (I-6). It can only add a warning, and at the
  -- 1m timeframe news features are not read at all (condition 8).
  if p_timeframe <> '1m' then
    select c.kind, c.title, c.occurs_at, c.severity into v_catalyst
      from public.catalysts c
      where c.instrument_id = p_instrument
        and c.occurs_at between now() and now() + interval '24 hours'
      order by c.occurs_at
      limit 1;

    if found then
      v_warnings := v_warnings || jsonb_build_array(jsonb_build_object(
        'kind', 'catalyst',
        'severity', v_catalyst.severity,
        'text', format('%s: %s (%s)',
                       v_catalyst.kind, v_catalyst.title,
                       to_char(v_catalyst.occurs_at, 'DD Mon HH24:MI')),
        'at', v_catalyst.occurs_at
      ));
    end if;
  end if;

  if v_quote.bid is not null and v_quote.ask is not null and v_mid > 0 then
    if (v_quote.ask - v_quote.bid) / v_mid > 0.005 then
      v_warnings := v_warnings || jsonb_build_array(jsonb_build_object(
        'kind', 'spread',
        'severity', 'medium',
        'text', format('Spread is %s%% of price. Wide.',
                       round(((v_quote.ask - v_quote.bid) / v_mid) * 100, 3))
      ));
    end if;
  end if;

  -- --------------------------------------------------------- the metrics ---
  select jsonb_build_object(
    'trades', p.trades,
    'win_rate', p.win_rate,
    'expectancy', p.expectancy,
    'sharpe', p.sharpe,
    'max_drawdown', p.max_drawdown,
    'dsr', p.dsr,
    'pbo', p.pbo,
    'n_trials', p.n_trials,
    'period_start', p.period_start,
    'period_end', p.period_end,
    'benchmark', p.benchmark,
    'benchmark_return', p.benchmark_ret,
    'data_source', p.data_source
  ) into v_metric
  from public.performance p
  where p.version_id = v_version.id
    and p.timeframe = p_timeframe
  order by p.as_of desc
  limit 1;

  v_metric := coalesce(v_metric, jsonb_build_object(
    'trades', null,
    'note', 'No published performance record for this version yet.'
  ));

  -- ------------------------------------------------------------ the ticket --
  return jsonb_build_object(
    'status', 'ticket',
    'instrument', v_instr.symbol,
    'instrument_id', v_instr.id,
    'asset_class', v_instr.asset_class,
    'timeframe', p_timeframe,
    'side', v_signal.side,
    'entry_price', v_signal.entry_price,
    'entry_low', v_signal.entry_low,
    'entry_high', v_signal.entry_high,
    'stop_price', v_signal.stop_price,
    'target_price', v_signal.target_price,
    'target_2_price', v_signal.target_2_price,
    'size_units', v_size_units,
    'size_notional', v_size_notional,
    'risk_amount', v_risk_amount,
    'stop_distance', v_stop_distance,
    'reward_risk', v_rr,
    'confidence', v_signal.confidence,
    'strategy_id', v_strategy.id,
    'strategy_name', v_strategy.name,
    'strategy_family', v_strategy.family,
    'version_id', v_version.id,
    'version', v_version.version,
    'metrics', v_metric,
    'odds_band', v_signal.odds_band,
    'warnings', v_warnings,
    'data_source', v_quote.source,
    'data_quality', v_instr.data_quality,
    'data_as_of', v_quote.as_of,
    'signal_bar_close_time', v_signal.bar_close_time,
    'signal_id', v_signal.id,
    'engine', v_eng
  );
end;
$$;
-- ------------------------------------------------------- caller role ------
-- Who is calling? PostgREST applies `set local role <jwt role>` per request,
-- so the `role` GUC is the caller's role. Supabase also exposes the decoded
-- JWT as `request.jwt.claims`, and the individual claims as
-- `request.jwt.claim.<name>`. All three are read, most specific first.
--
-- `current_user` is NOT usable here: inside a SECURITY DEFINER function it is
-- the function owner (postgres), not the caller.
create or replace function public.caller_role()
returns text
language plpgsql
stable
security invoker
set search_path = public
as $$
declare
  v_role   text;
  v_claims text;
begin
  v_role := nullif(current_setting('request.jwt.claim.role', true), '');

  if v_role is null then
    v_claims := nullif(current_setting('request.jwt.claims', true), '');
    if v_claims is not null then
      begin
        v_role := nullif(v_claims::jsonb ->> 'role', '');
      exception when others then
        v_role := null;
      end;
    end if;
  end if;

  if v_role is null then
    v_role := nullif(current_setting('role', true), '');
  end if;

  return coalesce(v_role, '');
end;
$$;

-- ------------------------------------------------------ privileged --------
-- A caller is privileged when it is the worker, or when it is a direct
-- database session rather than an API request.
--
-- PostgREST applies `set local role <jwt role>` per request, so the `role`
-- setting is never 'none' for an API request: it is 'anon', 'authenticated'
-- or 'service_role'. A 'none' setting means no SET ROLE was applied, which is
-- a direct psql/session connection: the DBA, who can already do anything and
-- who is how the migration, the backup tool and the test harness call these
-- functions.
create or replace function public.caller_is_privileged()
returns boolean
language sql
stable
security invoker
set search_path = public
as $$
  select public.caller_role() in ('service_role', 'none', 'postgres');
$$;

-- =============================================================== grants ====
-- The rule this file enforces: a SECURITY DEFINER function in `public` is a
-- PUBLIC API ENDPOINT unless its EXECUTE grant says otherwise.

-- Worker-only. These are called by the live worker over the service-role key.
revoke all on function public.record_signal(uuid, text, public.signal_side, numeric, text,
  timestamptz, timestamptz, text, numeric, numeric, numeric, numeric, numeric, numeric,
  uuid, jsonb, jsonb, timestamptz) from public, anon, authenticated;
grant execute on function public.record_signal(uuid, text, public.signal_side, numeric, text,
  timestamptz, timestamptz, text, numeric, numeric, numeric, numeric, numeric, numeric,
  uuid, jsonb, jsonb, timestamptz) to service_role;

revoke all on function public.claim_jobs(text, integer) from public, anon, authenticated;
grant execute on function public.claim_jobs(text, integer) to service_role;

revoke all on function public.finish_job(uuid, boolean, jsonb, text) from public, anon, authenticated;
grant execute on function public.finish_job(uuid, boolean, jsonb, text) to service_role;

-- User-facing, and each one is guarded by its own custody check.
revoke all on function public.get_ticket(uuid, uuid, text) from public, anon;
grant execute on function public.get_ticket(uuid, uuid, text) to authenticated, service_role;

revoke all on function public.fire_alert(uuid, text, text, text, text, public.alert_severity, jsonb, text)
  from public, anon;
grant execute on function public.fire_alert(uuid, text, text, text, text, public.alert_severity, jsonb, text)
  to authenticated, service_role;

revoke all on function public.promote_strategy(uuid, text) from public, anon;
grant execute on function public.promote_strategy(uuid, text) to authenticated;

-- Helpers used by RLS policies. They must be callable by the policy, and by
-- nobody else.
revoke all on function public.is_owner() from public, anon;
grant execute on function public.is_owner() to authenticated, service_role;

revoke all on function public.is_owner_or_self(uuid) from public, anon;
grant execute on function public.is_owner_or_self(uuid) to authenticated, service_role;

revoke all on function public.engine_status() from public, anon;
grant execute on function public.engine_status() to authenticated, service_role;

-- A trigger function. No role has any business calling it.
revoke all on function public.set_updated_at() from public, anon, authenticated;

-- The helper above is called by the guards in this migration.
revoke all on function public.caller_role() from public, anon;
grant execute on function public.caller_role() to authenticated, service_role;

revoke all on function public.caller_is_privileged() from public, anon;
grant execute on function public.caller_is_privileged() to authenticated, service_role;

-- ================================================== future-proofing =======
-- Without this, every function created after this migration is EXECUTE-able by
-- `anon` again, by default. This is the root cause, so close it at the source.
alter default privileges in schema public revoke execute on functions from anon, authenticated;
alter default privileges in schema public revoke all on functions from public;
