"""The strategy contract.

This file is FIXED. It is never written by an AI. It defines the interface
that every strategy — human-written, parameter-mutated, or generated by a
model inside a sandbox — must satisfy.

Why the contract is narrow on purpose:

  * `ctx` carries only what a strategy needs to decide. No filesystem, no
    network, no database, no clock beyond the bar timestamp.
  * `Signal` carries only a side, a stop, a target and a confidence. It has no
    field for "size", because sizing belongs to the Postgres RPC, which is
    the single implementation of the risk maths.
  * A strategy that returns `None` means "no opinion". That is a normal,
    expected outcome, not a failure.

If you extend this, extend it here and nowhere else.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Mapping, Sequence


@dataclass(frozen=True)
class Bar:
    """One closed bar. Strategies only ever see CLOSED bars."""

    ts: datetime
    open: float
    high: float
    low: float
    close: float
    volume: float = 0.0


@dataclass(frozen=True)
class Position:
    """The position the strategy currently holds, if any."""

    side: str  # 'buy' | 'sell' | 'flat'
    entry_price: float
    size: float
    opened_at: datetime | None = None

    @property
    def is_flat(self) -> bool:
        return self.side == "flat" or self.size == 0


@dataclass(frozen=True)
class Signal:
    """A strategy's opinion.

    Deliberately minimal. Note what is ABSENT:

      * no `size`   -- sizing is the database's job (I-5)
      * no `order`  -- the worker never places orders
      * no `reason` -- that is added by the caller, after the fact

    `stop_price` is required for any non-flat signal. A signal without a stop
    is refused by the ticket function, because a trade without a stop is not a
    trade, it is a wish.
    """

    side: str  # 'buy' | 'sell' | 'flat'
    stop_price: float | None = None
    target_price: float | None = None
    target_2_price: float | None = None
    confidence: float | None = None
    entry_low: float | None = None
    entry_high: float | None = None
    rule_id: str = "unknown"
    notes: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.side not in ("buy", "sell", "flat"):
            raise ValueError(f"Invalid side '{self.side}'. Use buy, sell or flat.")
        if self.side != "flat" and self.stop_price is None:
            raise ValueError(
                "A non-flat signal must carry a stop_price. "
                "A trade without a stop is not a trade."
            )
        if self.confidence is not None and not (0.0 <= self.confidence <= 1.0):
            raise ValueError(f"confidence must be between 0 and 1, got {self.confidence}")


@dataclass
class Context:
    """Everything a strategy is allowed to see.

    No filesystem. No network. No database. No wall clock: `now` is the
    timestamp of the bar being evaluated, so a backtest and a live run see
    exactly the same information.
    """

    symbol: str
    timeframe: str
    bars: Sequence[Bar]
    position: Position
    params: Mapping[str, Any]
    now: datetime
    # Derived series the engine computed, indexed to align with `bars`.
    indicators: Mapping[str, Sequence[float]] = field(default_factory=dict)
    # Secondary series, keyed by symbol. A rotation strategy needs the
    # defensive leg (QQQ and GLD); a pairs strategy needs its partner.
    aux_bars: Mapping[str, Sequence[Bar]] = field(default_factory=dict)
    # Auxiliary indicators, keyed by "<symbol>:<name>".
    aux_indicators: Mapping[str, Sequence[float]] = field(default_factory=dict)

    def last_bar(self) -> Bar | None:
        return self.bars[-1] if self.bars else None

    def closes(self, n: int | None = None) -> list[float]:
        if not self.bars:
            return []
        return [b.close for b in (self.bars[-n:] if n else self.bars)]

    def indicator(self, name: str, index: int = -1) -> float | None:
        series = self.indicators.get(name)
        if not series:
            return None
        try:
            return series[index]
        except IndexError:
            return None

    def aux_closes(self, symbol: str, n: int | None = None) -> list[float]:
        """Closes of a secondary series, aligned to the END of the series.

        Alignment is by POSITION FROM THE END, not by timestamp: the two
        series may have different session calendars (QQQ trades 6.5h, GLD the
        same, but FX trades 24h), and a timestamp join would silently drop
        bars.
        """
        series = self.aux_bars.get(symbol)
        if not series:
            return []
        return [b.close for b in (series[-n:] if n else series)]

    def aux_indicator(self, symbol: str, name: str, index: int = -1) -> float | None:
        series = self.aux_indicators.get(f"{symbol}:{name}")
        if not series:
            return None
        try:
            return series[index]
        except IndexError:
            return None

    def ready(self, minimum_bars: int) -> bool:
        """True when there is enough history to decide."""
        return len(self.bars) >= minimum_bars


class Strategy:
    """The base class every strategy extends.

    Subclasses implement `on_bar`. They must be deterministic: the same
    context must always produce the same signal, or the backtest result is
    not reproducible and the gate has nothing to trust.
    """

    # How many bars of history the strategy needs before it will speak.
    min_bars: int = 50
    # The parameters this strategy accepts, with their defaults.
    defaults: dict[str, Any] = {}

    def __init__(self, params: Mapping[str, Any] | None = None) -> None:
        merged = dict(self.defaults)
        merged.update(dict(params or {}))
        self.params = merged

    def on_bar(self, ctx: Context) -> Signal | None:
        """Return a Signal, or None for no opinion."""
        raise NotImplementedError

    # --------------------------------------------------------- utilities --

    @staticmethod
    def ema(values: Sequence[float], period: int) -> list[float]:
        from ..indicators import ema as _ema

        return _ema(values, period)

    @staticmethod
    def atr(bars: Sequence[Bar], period: int = 14) -> list[float]:
        from ..indicators import atr as _atr

        return _atr(bars, period)
